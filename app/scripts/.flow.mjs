import { chromium } from '@playwright/test';
const [url, dir] = process.argv.slice(2);
const b = await chromium.launch({ channel: 'chrome' });
const p = await b.newPage({ viewport: { width: 390, height: 844 }, colorScheme: 'dark' });
await p.goto(url, { waitUntil: 'networkidle' });
await p.evaluate(() => localStorage.clear());
await p.reload({ waitUntil: 'networkidle' });
const shot = async (n) => { await p.waitForTimeout(700); await p.screenshot({ path: `${dir}/${n}.png` }); };
const keys = async (s) => { for (const k of s) await p.keyboard.press(k === '\n' ? 'Enter' : k === ' ' ? 'Space' : k); };
await shot('f01-menu-first');
await p.getByRole('button', { name: /Learn to play/ }).click();
await shot('f02-learn-intro');
await keys('\n'); await keys('te'); await shot('f03-learn-team-typing');
await keys('am\n'); await shot('f04-learn-watch-dog');
await keys('\n'); await keys('map'); await shot('f05-learn-map-flip');
await keys(' \n\n'); await keys('top\n'); await keys('cat'); await shot('f06-learn-bump');
await keys('\n'); await keys('pope'); await shot('f07-learn-pope-ready');
await keys('\n'); await shot('f08-learn-won');
await keys('\n'); await shot('f09-learn-done');
await p.getByRole('button', { name: 'Back to menu' }).click();
await p.getByRole('button', { name: /New game/ }).click();
await keys('team\n'); await p.waitForTimeout(300);
await p.getByRole('button', { name: 'Menu and settings' }).click(); await shot('f10-game-sheet');
await p.getByRole('button', { name: 'Back to menu' }).click(); await shot('f11-menu-returning');
await b.close();
