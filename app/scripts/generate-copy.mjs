/**
 * Generates src/copy/deck.ts from the design handoff's copy deck, so the app always uses
 * the deck's exact wording. Run after the deck changes: npm run copy
 *
 * Rows whose ID describes several strings at once (e.g. "settings.theme.auto / light / dark",
 * "gsettings.hints.*") can't be mapped automatically; they're listed in src/copy/overrides.ts.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const deckPath = fileURLToPath(new URL('../../design/handoff/wordrush-copy-deck.md', import.meta.url));
const outPath = fileURLToPath(new URL('../src/copy/deck.ts', import.meta.url));

const text = readFileSync(deckPath, 'utf8');
const body = text.split(/^## 4\. Glossary/m)[0]; // the glossary table has a different shape
const entries = [];
const skipped = [];
for (const line of body.split('\n')) {
  const cells = line.split('|').map((c) => c.trim());
  if (cells.length !== 6 || cells[1] === 'ID' || cells[1].startsWith('---')) continue;
  const [, id, , , value] = cells;
  if (!/^[a-zA-Z0-9.]+$/.test(id)) {
    skipped.push(id);
    continue;
  }
  entries.push([id, value]);
}

const lines = entries.map(([id, value]) => `  ${JSON.stringify(id)}: ${JSON.stringify(value)},`);
writeFileSync(
  outPath,
  `/* Generated by scripts/generate-copy.mjs from design/handoff/wordrush-copy-deck.md. Don't edit. */\n\n` +
    `export const deck = {\n${lines.join('\n')}\n} as const;\n`,
);
console.log(`copy: ${entries.length} strings written; skipped composite IDs: ${skipped.join(', ')}`);
